"""Generate the Agentverse-hosted agents from the dermis_agents package.

  python tools/build_hosted.py --snapshot-url https://raw.githubusercontent.com/.../dermis_snapshot.json

Writes hosted/<key>/ for each hosted agent: agent.py (bootstrap), the runtime modules flattened to
dermis_*.py (hosted agents import files flatly, not as a package), README.md, pyproject.toml, .env
and .avctl/config.toml. The code is the same code run.py runs locally; only the imports are rewritten.
An agent's saved address in .avctl/config.toml is kept, so redeploying updates it instead of making
a new one. The hub gets the addresses of the specialists already deployed (deploy_hosted.py deploys
them first); specialists that aren't hosted run inside the hub.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dermis_agents import agents  # noqa: E402
from dermis_agents.profiles import BY_KEY  # noqa: E402

PKG = ROOT / "dermis_agents"
OUT = ROOT / "hosted"
URL_FILE = OUT / "snapshot_url.txt"

# Free Agentverse accounts hold 8 agents. Every other specialist still answers through the hub.
HOSTED = ["hub", "visualizer", "data_explorer", "humanoid_arm", "industrial_arm", "quadruped",
          "warehouse", "sensor_qa"]
# Agentverse @handles (lowercase letters, digits and hyphens; no underscores).
HANDLES = {"hub": "dermis-hub", "data_explorer": "dermis-analyst", "visualizer": "dermis-charts",
           "humanoid_arm": "dermis-humanoid", "industrial_arm": "dermis-industrial", "quadruped": "dermis-quadruped",
           "warehouse": "dermis-warehouse", "sensor_qa": "dermis-sensors"}
# Runtime modules (no numpy/pandas; features/data/snapshot are build-time only). agents.py is
# renamed so it can't be confused with the package name.
MODULES = {"config": "dermis_config", "profiles": "dermis_profiles", "store": "dermis_store",
           "analysis": "dermis_analysis", "charts": "dermis_charts", "llm": "dermis_llm", "viz": "dermis_viz",
           "brain": "dermis_brain", "dataset": "dermis_dataset", "connectors": "dermis_connectors",
           "cards": "dermis_cards", "payments": "dermis_payments",
           "specialist": "dermis_specialist", "hub": "dermis_hub", "agents": "dermis_uagents"}

AGENT_PY = '''"""{title} · Agentverse hosted agent.

GENERATED by tools/build_hosted.py from the dermis_agents package. Edit the package, rebuild, redeploy.
"""

import os

os.environ.setdefault("DERMIS_SNAPSHOT_URL", {url!r})

from uagents import Agent

from dermis_payments import set_wallet
from dermis_uagents import protocols_for, self_check

AGENT_KEY = {key!r}
# Specialists deployed as their own hosted agents (the hub asks them; any other runs inside the hub).
ADDRESSES = {addresses}

agent = Agent()
set_wallet(agent.wallet)  # receives the certified-report payments (hub)
for _protocol in protocols_for(AGENT_KEY, ADDRESSES):
    agent.include(_protocol, publish_manifest=True)


@agent.on_event("startup")
async def _self_check(ctx):
    ctx.logger.info(f"self-check: {{await self_check()}}")

if __name__ == "__main__":
    agent.run()
'''


def flatten(src: str) -> str:
    def from_dot_import(m: re.Match) -> str:
        names = [n.strip() for n in m.group(2).split(",")]
        return m.group(1) + "import " + ", ".join(f"{MODULES[n]} as {n}" for n in names)

    src = re.sub(r"^(\s*)from \. import (.+)$", from_dot_import, src, flags=re.M)
    src = re.sub(r"^(\s*)from \.(\w+) import ", lambda m: f"{m.group(1)}from {MODULES[m.group(2)]} import ", src, flags=re.M)
    if re.search(r"^\s*(from \.|import \.)", src, flags=re.M):
        raise SystemExit("unhandled relative import left after flattening")
    return src


def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def read_config(path: Path) -> dict:
    cfg = {}
    if path.exists():
        for line in path.read_text().splitlines():
            m = re.match(r'\s*(\w+)\s*=\s*"(.*)"\s*$', line)
            if m:
                cfg[m.group(1)] = m.group(2)
    return cfg


def deployed_address(key: str) -> str:
    return read_config(OUT / key / ".avctl" / "config.toml").get("address", "")


def build(url: str) -> list[Path]:
    flat = {name: flatten((PKG / f"{name}.py").read_text()) for name in MODULES}
    # No reliance on env vars for the data: the URL is written into the hosted config itself.
    marker = 'SNAPSHOT_URL = os.getenv("DERMIS_SNAPSHOT_URL", "")'
    assert marker in flat["config"], "config.py changed: update the snapshot URL baking"
    flat["config"] = flat["config"].replace(marker, f'SNAPSHOT_URL = os.getenv("DERMIS_SNAPSHOT_URL", {url!r})')
    hub_addresses = {k: a for k in HOSTED if k != "hub" and (a := deployed_address(k)).startswith("agent1")}
    folders = []
    for key in HOSTED:
        d = OUT / key
        (d / ".avctl").mkdir(parents=True, exist_ok=True)
        for name, text in flat.items():
            (d / f"{MODULES[name]}.py").write_text(text)
        name, title, body = agents.identity_of(key)
        addresses = json.dumps(hub_addresses if key == "hub" else {}, indent=4)
        (d / "agent.py").write_text(AGENT_PY.format(title=title, url=url, key=key, addresses=addresses))
        (d / "README.md").write_text(
            f"# {title}\n\n{agents.BADGES}\n\n{body}\n"
            "")
        (d / ".env").write_text("# No secrets needed: Agentverse injects ASI1_API_KEY and ASI1_BASE_URL.\n")
        (d / "pyproject.toml").write_text(
            f'[project]\nname = "{name.replace("_", "-")}"\nversion = "0.2.0"\ndescription = {toml_str(title)}\n'
            'readme = "README.md"\nrequires-python = ">=3.10,<3.13"\ndependencies = [\n'
            '    "uagents>=0.25.5",\n]\n')
        examples = (["Compare all applications on episode 4", "Show me a dashboard chart",
                     "Which items do we drop most in the warehouse?", "Pivot table of success by scenario",
                     "Are any sensor readings unreliable?"] if key == "hub" else list(BY_KEY[key].examples))[:5]
        description = (BY_KEY[key].domain if key != "hub" else
                       "Robot touch intelligence: routes Dermis tactile-sensor questions to specialist agents "
                       "for humanoid, industrial, quadruped, warehouse and more, with charts and tables.")
        old = read_config(d / ".avctl" / "config.toml")
        (d / ".avctl" / "config.toml").write_text(
            "[agent]\n"
            f"  address = {toml_str(old.get('address', ''))}\n"
            '  include = ""\n'
            '  readme_path = "README.md"\n'
            f"  description = {toml_str(description[:300])}\n"
            f"  starter_prompts = [{', '.join(toml_str(e[:200]) for e in examples)}]\n")
        folders.append(d)
    return folders


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--snapshot-url", help="public URL of snapshot/dermis_snapshot.json (remembered)")
    args = ap.parse_args()
    url = args.snapshot_url or (URL_FILE.read_text().strip() if URL_FILE.exists() else "")
    if not url:
        sys.exit("Pass --snapshot-url once (the public URL of snapshot/dermis_snapshot.json).")
    OUT.mkdir(exist_ok=True)
    URL_FILE.write_text(url + "\n")
    for d in build(url):
        addr = deployed_address(d.name)
        print(f"  {d.relative_to(ROOT)}  {addr or '(not deployed yet)'}")
    print(f"Built {len(HOSTED)} hosted agents · snapshot {url}")


if __name__ == "__main__":
    main()
